"""Comptes propres au pilotage, sessions revocables et audit dans PostgreSQL."""
from contextlib import contextmanager
import hashlib
import hmac
import math
import re
import secrets
import sqlite3
import time

from .db import load_config, raw_connect
from .passwords import hash_password, verify_password

SCHEMA = "pilotage_auth"
APPLICATION_ID = 0x4D4F4155
SESSION_SECONDS = 8 * 3600
IDLE_SECONDS = 30 * 60
SESSION_PATTERN = re.compile(r"^[A-Za-z0-9_-]{43}$")
PUBLIC_FIELDS = ("id", "username", "display_name", "role", "active", "created_at", "updated_at")
# Hachage d'une chaine sans compte associe : meme travail pour un identifiant inconnu.
DUMMY_HASH = "$argon2id$v=19$m=19456,t=2,p=1$mtoEymtK5lvaLpEuGh015w$Jcn6TM+gbzUMZBIMby7ESQvQXX4CnD9xdpczh5ep+Ug"
DDL = (
    "CREATE TABLE schema_info(id INTEGER PRIMARY KEY CHECK(id=1), version INTEGER NOT NULL, application_id INTEGER NOT NULL)",
    """CREATE TABLE users(
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username TEXT UNIQUE NOT NULL, display_name TEXT NOT NULL,
        role TEXT NOT NULL CHECK(role IN ('admin','reader')), active BOOLEAN NOT NULL DEFAULT TRUE,
        password_hash TEXT NOT NULL, version INTEGER NOT NULL DEFAULT 1,
        created_at DOUBLE PRECISION NOT NULL, updated_at DOUBLE PRECISION NOT NULL)""",
    """CREATE TABLE sessions(
        token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
        user_version INTEGER NOT NULL, created_at DOUBLE PRECISION NOT NULL,
        last_seen_at DOUBLE PRECISION NOT NULL, expires_at DOUBLE PRECISION NOT NULL)""",
    "CREATE INDEX sessions_user ON sessions(user_id)",
    """CREATE TABLE login_limits(
        key TEXT PRIMARY KEY, window_at DOUBLE PRECISION NOT NULL, attempts INTEGER NOT NULL)""",
    """CREATE TABLE events(
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        actor_id BIGINT REFERENCES users(id), target_id BIGINT REFERENCES users(id),
        action TEXT NOT NULL, observed_at DOUBLE PRECISION NOT NULL)""",
)


class AuthStorageError(RuntimeError):
    pass


class AuthDenied(ValueError):
    pass


class AuthConflict(ValueError):
    pass


class AuthThrottled(ValueError):
    pass


def timestamp(now=None):
    value = time.time() if now is None else now
    if type(value) not in (int, float) or not math.isfinite(value) or value < 0:
        raise ValueError("Date invalide.")
    return float(value)


def username(value):
    if not isinstance(value, str):
        raise ValueError("Identifiant invalide.")
    value = value.strip().lower()
    if not re.fullmatch(r"[a-z][a-z0-9_.-]{2,31}", value):
        raise ValueError("Identifiant : 3 a 32 lettres, chiffres, points, tirets ou underscores.")
    return value


def public_user(row):
    return {key: row[key] for key in PUBLIC_FIELDS}


def csrf_token(token):
    return hmac.new(token.encode("ascii"), b"moodle-pilotage/csrf/v1", hashlib.sha256).hexdigest()


def session_hash(token):
    return hashlib.sha256(token.encode("ascii")).hexdigest()


class AuthStore:
    def __init__(self, *, database_config=None):
        try:
            self.config = load_config(database_config)
        except sqlite3.Error:
            raise AuthStorageError("Configuration des comptes indisponible.") from None
        if self.config is None:
            raise AuthStorageError("PostgreSQL est requis pour les comptes du pilotage.")

    @staticmethod
    def check_schema(connection):
        if connection.execute("SELECT version,application_id FROM schema_info WHERE id=1").fetchone() != (1, APPLICATION_ID):
            raise AuthStorageError("Schema des comptes incompatible.")

    @contextmanager
    def connection(self, *, write=False):
        import psycopg
        from psycopg.rows import dict_row
        try:
            with raw_connect(self.config, read_only=not write) as connection:
                with connection.transaction():
                    if write:
                        connection.execute("SELECT pg_advisory_xact_lock(%s,0)", (APPLICATION_ID,))
                    connection.execute("SET LOCAL search_path TO pilotage_auth, pg_catalog")
                    self.check_schema(connection)
                    with connection.cursor(row_factory=dict_row) as cursor:
                        yield cursor
        except (sqlite3.Error, psycopg.Error) as exc:
            raise AuthStorageError("Stockage des comptes indisponible.") from None

    def initialize(self):
        import psycopg
        try:
            with raw_connect(self.config) as connection:
                with connection.transaction():
                    connection.execute("SELECT pg_advisory_xact_lock(%s,0)", (APPLICATION_ID,))
                    exists = connection.execute("SELECT to_regnamespace(%s)", (SCHEMA,)).fetchone()[0]
                    if exists is not None:
                        connection.execute("SET LOCAL search_path TO pilotage_auth, pg_catalog")
                        self.check_schema(connection)
                        return False
                    connection.execute("CREATE SCHEMA pilotage_auth")
                    connection.execute("SET LOCAL search_path TO pilotage_auth, pg_catalog")
                    for statement in DDL:
                        connection.execute(statement)
                    connection.execute("INSERT INTO schema_info VALUES(1,1,%s)", (APPLICATION_ID,))
                    return True
        except (sqlite3.Error, psycopg.Error):
            raise AuthStorageError("Initialisation des comptes indisponible.") from None

    def check(self):
        with self.connection() as cursor:
            cursor.execute("SELECT 1")

    @staticmethod
    def actor(cursor, actor_id):
        if actor_id is None:  # Commande locale protegee par les droits root.
            return
        row = cursor.execute("SELECT role,active FROM users WHERE id=%s", (actor_id,)).fetchone()
        if row is None or not row["active"] or row["role"] != "admin":
            raise AuthDenied("Droits administrateur requis.")

    @staticmethod
    def event(cursor, action, now, actor_id=None, target_id=None):
        cursor.execute("INSERT INTO events(actor_id,target_id,action,observed_at) VALUES(%s,%s,%s,%s)",
                       (actor_id, target_id, action, now))

    def users(self, *, actor_id=None):
        with self.connection() as cursor:
            self.actor(cursor, actor_id)
            return [public_user(row) for row in cursor.execute("SELECT * FROM users ORDER BY id")]

    def add_user(self, name, display_name, role, password, *, actor_id=None, now=None):
        name, now = username(name), timestamp(now)
        if role not in ("admin", "reader"):
            raise ValueError("Role invalide.")
        if not isinstance(display_name, str) or not 1 <= len(display_name.strip()) <= 80 or any(ord(c) < 32 for c in display_name):
            raise ValueError("Nom affiche invalide.")
        encoded = hash_password(password)
        with self.connection(write=True) as cursor:
            self.actor(cursor, actor_id)
            row = cursor.execute("""INSERT INTO users(username,display_name,role,password_hash,created_at,updated_at)
                VALUES(%s,%s,%s,%s,%s,%s) ON CONFLICT(username) DO NOTHING RETURNING *""",
                (name, display_name.strip(), role, encoded, now, now)).fetchone()
            if row is None:
                raise AuthConflict("Cet identifiant existe deja.")
            self.event(cursor, "user_created", now, actor_id, row["id"])
            return public_user(row)

    def update_user(self, identifier, *, actor_id=None, role=None, active=None, now=None):
        if type(identifier) is not int or identifier < 1 or (role is None and active is None):
            raise ValueError("Modification invalide.")
        if role not in (None, "admin", "reader") or (active is not None and type(active) is not bool):
            raise ValueError("Modification invalide.")
        now = timestamp(now)
        with self.connection(write=True) as cursor:
            self.actor(cursor, actor_id)
            row = cursor.execute("SELECT * FROM users WHERE id=%s", (identifier,)).fetchone()
            if row is None:
                raise AuthConflict("Compte inconnu.")
            target_role = role if role is not None else row["role"]
            target_active = active if active is not None else row["active"]
            if actor_id == identifier:
                if not target_active:
                    raise AuthConflict("Vous ne pouvez pas désactiver votre propre compte.")
                if target_role != row["role"]:
                    raise AuthConflict("Vous ne pouvez pas modifier votre propre rôle.")
            if row["role"] == "admin" and row["active"] and (target_role != "admin" or not target_active):
                others = cursor.execute("SELECT count(*) AS count FROM users WHERE role='admin' AND active AND id<>%s",
                                        (identifier,)).fetchone()["count"]
                if others == 0:
                    raise AuthConflict("Conserver au moins un administrateur actif.")
            if (target_role, target_active) == (row["role"], row["active"]):
                return public_user(row)
            row = cursor.execute("""UPDATE users SET role=%s,active=%s,version=version+1,updated_at=%s
                WHERE id=%s RETURNING *""", (target_role, target_active, now, identifier)).fetchone()
            cursor.execute("DELETE FROM sessions WHERE user_id=%s", (identifier,))
            self.event(cursor, "user_updated", now, actor_id, identifier)
            return public_user(row)

    def reserve_login(self, name, now):
        keys = (("global", 60, 30), ("user:" + hashlib.sha256(name.encode()).hexdigest(), 300, 5))
        with self.connection(write=True) as cursor:
            cursor.execute("DELETE FROM login_limits WHERE window_at<%s", (now - 3600,))
            pending = []
            for key, window, limit in keys:
                row = cursor.execute("SELECT * FROM login_limits WHERE key=%s", (key,)).fetchone()
                if row and (now < row["window_at"] or (now - row["window_at"] < window and row["attempts"] >= limit)):
                    return False
                start = row["window_at"] if row and now - row["window_at"] < window else now
                count = row["attempts"] + 1 if row and start == row["window_at"] else 1
                pending.append((key, start, count))
            for values in pending:
                cursor.execute("""INSERT INTO login_limits VALUES(%s,%s,%s) ON CONFLICT(key)
                    DO UPDATE SET window_at=excluded.window_at,attempts=excluded.attempts""", values)
            return True

    @staticmethod
    def issue(cursor, row, now):
        token = secrets.token_urlsafe(32)
        cursor.execute("DELETE FROM sessions WHERE expires_at<=%s OR last_seen_at<=%s", (now, now - IDLE_SECONDS))
        cursor.execute("INSERT INTO sessions VALUES(%s,%s,%s,%s,%s,%s)",
                       (session_hash(token), row["id"], row["version"], now, now, now + SESSION_SECONDS))
        return {"user": public_user(row), "csrf_token": csrf_token(token), "token": token,
                "expires_at": now + SESSION_SECONDS}

    def login(self, name, password, *, now=None):
        name, now = username(name), timestamp(now)
        if not self.reserve_login(name, now):
            raise AuthThrottled("Trop de tentatives. Reessayer dans quelques minutes.")
        with self.connection() as cursor:
            row = cursor.execute("SELECT * FROM users WHERE username=%s", (name,)).fetchone()
        valid = verify_password(row["password_hash"] if row else DUMMY_HASH, password)
        if not valid or not row or not row["active"]:
            with self.connection(write=True) as cursor:
                self.event(cursor, "login_failed", now, target_id=row["id"] if row else None)
            raise AuthDenied("Identifiant ou mot de passe incorrect.")
        with self.connection(write=True) as cursor:
            current = cursor.execute("SELECT * FROM users WHERE id=%s", (row["id"],)).fetchone()
            if not current or not current["active"] or current["version"] != row["version"]:
                raise AuthDenied("Identifiant ou mot de passe incorrect.")
            cursor.execute("DELETE FROM login_limits WHERE key=%s", ("user:" + hashlib.sha256(name.encode()).hexdigest(),))
            result = self.issue(cursor, current, now)
            self.event(cursor, "login_succeeded", now, current["id"], current["id"])
            return result

    def authenticate(self, token, *, now=None):
        if not isinstance(token, str) or not SESSION_PATTERN.fullmatch(token):
            raise AuthDenied("Connexion requise.")
        fingerprint = session_hash(token)
        with self.connection(write=True) as cursor:
            # Echantillonner apres le verrou : une requete concurrente peut avoir
            # deja avance last_seen_at pendant l'attente de cette transaction.
            now = timestamp(now)
            row = cursor.execute("""SELECT users.*,sessions.user_version,sessions.created_at AS session_created_at,
                sessions.last_seen_at,sessions.expires_at FROM sessions JOIN users ON users.id=sessions.user_id
                WHERE token_hash=%s""", (fingerprint,)).fetchone()
            if (row is None or not row["active"] or row["version"] != row["user_version"]
                    or now < max(row["session_created_at"], row["last_seen_at"])
                    or now >= row["expires_at"] or now - row["last_seen_at"] >= IDLE_SECONDS):
                raise AuthDenied("Session expiree. Reconnectez-vous.")
            cursor.execute("UPDATE sessions SET last_seen_at=%s WHERE token_hash=%s", (now, fingerprint))
            return {"user": public_user(row), "csrf_token": csrf_token(token),
                    "session_hash": fingerprint, "version": row["version"]}

    def logout(self, principal, *, now=None):
        with self.connection(write=True) as cursor:
            cursor.execute("DELETE FROM sessions WHERE token_hash=%s", (principal["session_hash"],))
            self.event(cursor, "logout", timestamp(now), principal["user"]["id"], principal["user"]["id"])

    def set_password(self, name, password, *, now=None):
        """Recuperation locale root ; toutes les sessions existantes sont revoquees."""
        name, now, encoded = username(name), timestamp(now), hash_password(password)
        with self.connection(write=True) as cursor:
            row = cursor.execute("""UPDATE users SET password_hash=%s,version=version+1,updated_at=%s
                WHERE username=%s RETURNING *""", (encoded, now, name)).fetchone()
            if row is None:
                raise AuthConflict("Compte inconnu.")
            cursor.execute("DELETE FROM sessions WHERE user_id=%s", (row["id"],))
            self.event(cursor, "password_reset_local", now, target_id=row["id"])
            return public_user(row)

    def change_password(self, principal, old_password, new_password, *, now=None):
        now = timestamp(now)
        identifier = principal["user"]["id"]
        with self.connection() as cursor:
            row = cursor.execute("SELECT * FROM users WHERE id=%s", (identifier,)).fetchone()
        if not row or not self.reserve_login(row["username"], now):
            raise AuthThrottled("Trop de tentatives. Reessayer dans quelques minutes.")
        if not verify_password(row["password_hash"], old_password):
            raise AuthDenied("Mot de passe actuel incorrect.")
        encoded = hash_password(new_password)
        with self.connection(write=True) as cursor:
            current = cursor.execute("SELECT * FROM users WHERE id=%s", (identifier,)).fetchone()
            if not current or not current["active"] or current["version"] != principal["version"]:
                raise AuthDenied("Session expiree. Reconnectez-vous.")
            current = cursor.execute("""UPDATE users SET password_hash=%s,version=version+1,updated_at=%s
                WHERE id=%s RETURNING *""", (encoded, now, identifier)).fetchone()
            cursor.execute("DELETE FROM sessions WHERE user_id=%s", (identifier,))
            result = self.issue(cursor, current, now)
            self.event(cursor, "password_changed", now, identifier, identifier)
            return result

    def events(self, *, actor_id, limit=50):
        if type(limit) is not int or not 1 <= limit <= 100:
            raise ValueError("Pagination invalide.")
        with self.connection() as cursor:
            self.actor(cursor, actor_id)
            return list(cursor.execute("SELECT * FROM events ORDER BY id DESC LIMIT %s", (limit,)))
