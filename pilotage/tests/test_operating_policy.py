def document(incident=5):
    iso=lambda t: datetime.fromtimestamp(t,timezone.utc).isoformat()
    return {"status":"available","snapshot_usable":True,"mode":"simulation","policy_sha256":"b"*64,
        "decision":{"incident_id":incident,"signal_key":"moodle_https","status":"recommendation",
            "incident_status":"open","latest_state":"triggered","evidence":{"probe_success":False},
            "recommended_action":{"id":"diagnose_moodle_https"},"decision_id":"c"*64,"policy_sha256":"b"*64,
            "context":"policy-v1","input_evaluated_at":iso(BASE),"valid_until":iso(BASE+90)}}


class Cursor:
    def __init__(self,connection): self.connection=connection
    def execute(self,query,args=()):
        query=query.replace("%s","?").replace("pilotage_auth.users","users").replace("pilotage_auth.sessions","sessions")
        query=query.replace(" FOR SHARE OF u,s","")
        query=query.replace(" FOR SHARE OF u","")
        self.cursor=self.connection.execute(query,args)
        return self
    @staticmethod
    def row(row):
        if row is None: return None
        result=dict(row)
        for key in ("suspended","evaluation_context","active"):
            if key in result: result[key]=bool(result[key])
        return result
    def fetchone(self): return self.row(self.cursor.fetchone())
    def fetchall(self): return [self.row(row) for row in self.cursor.fetchall()]


class FixtureStore(PolicyStore):
    def __init__(self):
        self.lock=threading.RLock()
        self.sql=sqlite3.connect(":memory:",isolation_level=None,check_same_thread=False)
        self.sql.row_factory=sqlite3.Row
        self.sql.execute("PRAGMA foreign_keys=ON")
        self.sql.execute("CREATE TABLE users(id INTEGER PRIMARY KEY,username TEXT,active BOOLEAN,role TEXT,version INTEGER)")
        self.sql.execute("INSERT INTO users VALUES(1,'hamma',1,'admin',1)")
        self.sql.execute("CREATE TABLE sessions(token_hash TEXT PRIMARY KEY,user_id INTEGER,user_version INTEGER,created_at REAL,last_seen_at REAL,expires_at REAL)")
        self.sql.execute("INSERT INTO sessions VALUES(?,1,1,?,?,?)",("a"*64,BASE-60,BASE,BASE+10000))
        for statement in DDL:
            query=statement.replace("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY","INTEGER PRIMARY KEY AUTOINCREMENT")
            query=query.replace("pilotage_auth.users","users")
            self.sql.execute(query)
        row={"revision":1,"mode":"observation","suspended":False,"evaluation_context":False}
        self.sql.execute("INSERT INTO settings VALUES(1,1,'observation',false,false,?,NULL,'initialisation','Fixture initiale',?)",(BASE-100,digest(row)))

    @contextmanager
    def connection(self,*,write=False):
        with self.lock:
            self.sql.execute("BEGIN")
            try:
                yield Cursor(self.sql)
                self.sql.execute("COMMIT")
            except Exception as exc:
                self.sql.execute("ROLLBACK")
                if isinstance(exc,sqlite3.DatabaseError): raise PolicyStorageError("fixture SQL unavailable") from None
                raise


class PolicyTests(unittest.TestCase):
    def setUp(self):
        self.store=FixtureStore();self.addCleanup(self.store.sql.close)
    def update(self,**changes):
        kwargs=dict(revision=1,mode="assisted",suspended=False,evaluation_context=False,
            reason="Configurer le pilotage pour ce test",confirm_automatic=False,now=BASE+1)
        kwargs.update(changes)
        return self.store.update(PRINCIPAL,**kwargs)
    def approve(self,**changes):
        kwargs=dict(incident_id=5,revision=2,reason="Autoriser la reprise du service Moodle",client_key="d"*32,now=BASE+3)
        kwargs.update(changes)
        return self.store.approve(PRINCIPAL,document(),**kwargs)
    def dispatch(self,policy,**changes):
        kwargs=dict(run_id="e"*32,automatic=False,reserve=lambda:None,now=BASE+5)
        kwargs.update(changes)
        return self.store.dispatch(document(),policy,**kwargs)

    def test_observation_and_suspension_block_before_any_reservation(self):
        calls=[]
        initial=self.store.view(now=BASE)["policy"]
        with self.assertRaisesRegex(PolicyBlocked,"observation_mode"):
            self.dispatch(initial,reserve=lambda:calls.append(1))
        policy,_=self.update(suspended=True)
        with self.assertRaisesRegex(PolicyBlocked,"policy_suspended"):
            self.dispatch(policy,reserve=lambda:calls.append(1))
        self.assertEqual(calls,[]);self.assertEqual(self.store.sql.execute("SELECT count(*) FROM authorizations").fetchone()[0],0)

    def test_assisted_allows_manual_but_rejects_automatic_and_preserves_decision_proof(self):
        policy,_=self.update()
        with self.assertRaisesRegex(PolicyBlocked,"automatic_mode_not_active"): self.dispatch(policy,automatic=True)
        value=self.dispatch(policy)
        self.assertIsNone(value["approval_id"])
        self.assertEqual(self.store.history()["items"][0]["action"],"action_authorized")
        proof=self.store.sql.execute("SELECT decision_json,policy_json FROM authorizations").fetchone()
        self.assertIn("probe_success",proof[0]);self.assertIn(policy["sha256"],proof[1])

    def test_automatic_requires_confirmation_and_revalidates_policy_revision(self):
        with self.assertRaises(ValueError): self.update(mode="automatic")
        policy,_=self.update(mode="automatic",confirm_automatic=True)
        self.assertIsNotNone(self.store.reserve_worker(document(),now=BASE+2))
        self.assertIsNone(self.store.reserve_worker(document(),now=BASE+3))
        self.update(revision=2,mode="automatic",confirm_automatic=True,suspended=True,now=BASE+4)
        with self.assertRaises(PolicyBlocked): self.dispatch(policy,automatic=True)

    def test_evaluation_requires_current_single_use_approval(self):
        policy,_=self.update(evaluation_context=True)
        with self.assertRaisesRegex(PolicyBlocked,"evaluation_approval_required"): self.dispatch(policy)
        approval,created=self.approve();self.assertTrue(created)
        repeated,created=self.approve();self.assertFalse(created);self.assertEqual(repeated["id"],approval["id"])
        result=self.dispatch(policy);self.assertEqual(result["approval_id"],approval["id"])
        self.assertEqual(self.store.sql.execute("SELECT used_by FROM approvals").fetchone()[0],"e"*32)
        with self.assertRaises(PolicyBlocked): self.dispatch(policy,run_id="f"*32)

    def test_expiry_policy_change_and_approver_revocation_invalidate_approval(self):
        for change in ("expiry","revision","revocation"):
            with self.subTest(change=change):
                fresh=FixtureStore();old=self.store;self.store=fresh
                try:
                    policy,_=self.update(evaluation_context=True);self.approve()
                    now=BASE+5
                    if change=="expiry":now=BASE+91
                    elif change=="revision":self.update(revision=2,evaluation_context=False,now=BASE+4)
                    else:fresh.sql.execute("UPDATE users SET active=false WHERE id=1")
                    with self.assertRaises(PolicyBlocked):self.dispatch(policy,now=now)
                    self.assertEqual(fresh.sql.execute("SELECT count(*) FROM authorizations").fetchone()[0],0)
                finally:self.store=old;fresh.sql.close()

    def test_parallel_changes_cannot_overwrite_another_admin_revision(self):
        def change(_):
            try:self.update();return "changed"
            except PolicyConflict:return "conflict"
        with ThreadPoolExecutor(max_workers=2) as pool:results=list(pool.map(change,range(2)))
        self.assertEqual(sorted(results),["changed","conflict"])
        self.assertEqual(self.store.history()["total"],1)

    def test_revoked_reader_worker_or_wrong_session_cannot_modify_policy(self):
        for principal in ({"kind":"worker"},{**PRINCIPAL,"session_hash":"b"*64}):
            with self.assertRaises(AuthDenied):self.store.update(principal,revision=1,mode="assisted",suspended=False,
                evaluation_context=False,reason="Configurer ce test protege",now=BASE+1)
        self.store.sql.execute("UPDATE users SET role='reader'")
        with self.assertRaises(AuthDenied):self.update()
        self.assertEqual(self.store.history()["total"],0)

    def test_audit_failure_rolls_back_settings_and_authorization(self):
        self.store.sql.execute("CREATE TRIGGER audit_failure BEFORE INSERT ON events BEGIN SELECT RAISE(ABORT,'fixture'); END")
        with self.assertRaises(PolicyStorageError):self.update()
        self.assertEqual(self.store.view(now=BASE+2)["policy"]["revision"],1)

    def test_approval_client_key_cannot_be_reused_with_changed_reason(self):
        self.update(evaluation_context=True);self.approve()
        with self.assertRaises(PolicyConflict):self.approve(reason="Un autre motif pour ce meme incident")

    def test_missing_stale_unknown_statistical_or_mixed_decision_never_authorizes(self):
        for field,value in (("signal_key","statistical_anomaly"),("status","blocked"),("latest_state","unknown"),
                            ("valid_until","2020-01-01T00:00:00Z"),("incident_id",6)):
            bad=copy.deepcopy(document());bad["decision"][field]=value
            with self.assertRaises(PolicyBlocked):decision_reference(bad,5,BASE+2)
        bad=document();bad["snapshot_usable"]=False
        with self.assertRaises(PolicyBlocked):decision_reference(bad,5,BASE+2)

    def test_worker_age_is_visible_and_clock_reversal_is_not_healthy(self):
        self.assertEqual(self.store.view(now=BASE)["worker"]["status"],"unknown")
        self.store.heartbeat("idle",now=BASE)
        self.assertEqual(self.store.view(now=BASE+1)["worker"]["status"],"idle")
        self.assertEqual(self.store.view(now=BASE+91)["worker"]["status"],"stale")
        self.assertEqual(self.store.view(now=BASE-1)["worker"]["status"],"stale")

    def test_changed_policy_fingerprint_is_not_accepted(self):
        self.store.sql.execute("UPDATE settings SET mode='automatic'")
        with self.assertRaises(PolicyStorageError):self.store.view(now=BASE)

    def test_waiting_for_reservation_cannot_extend_approval_or_decision_validity(self):
        policy,_=self.update(evaluation_context=True);self.approve()
        with patch("pilotage.operating_policy.time.time",side_effect=[BASE+5,BASE+91]):
            with self.assertRaisesRegex(PolicyBlocked,"expired_before_dispatch"):
                self.dispatch(policy,now=None)
        self.assertIsNone(self.store.sql.execute("SELECT used_by FROM approvals").fetchone()[0])
        self.assertEqual(self.store.sql.execute("SELECT count(*) FROM authorizations").fetchone()[0],0)

    def test_clock_reversal_during_reservation_blocks_authorization(self):
        policy,_=self.update()
        with patch("pilotage.operating_policy.time.time",side_effect=[BASE+5,BASE+4]):
            with self.assertRaisesRegex(PolicyBlocked,"authorization_clock_inconsistent"):
                self.dispatch(policy,now=None)
        self.assertEqual(self.store.sql.execute("SELECT count(*) FROM authorizations").fetchone()[0],0)

    def test_evaluation_approval_is_bound_to_the_profile_action_not_only_the_incident(self):
        policy,_ = self.update(evaluation_context=True)
        self.approve()
        d = document()
        d['decision'].update(signal_key='php_pool_queue',recommended_action={'id':'diagnose_php_pool'},
            evidence={'pool':'www','idle_processes':0,'active_processes':5,'total_processes':5,'listen_queue':2})
        with self.assertRaisesRegex(PolicyBlocked,'evaluation_approval_required'):
            self.store.dispatch(d,policy,run_id='f'*32,automatic=False,reserve=lambda:None,now=BASE+5)
        approval,_ = self.store.approve(PRINCIPAL,d,incident_id=5,revision=2,
            reason='Approuver ce profil pour cet incident PHP',client_key='9'*32,now=BASE+5)
        self.assertEqual(approval['action_id'],PROFILE_ACTION)
        value = self.store.dispatch(d,policy,run_id='f'*32,automatic=False,reserve=lambda:None,now=BASE+6)
        self.assertEqual(value['approval_id'],approval['id'])
        self.assertEqual(self.store.history()['items'][0]['details']['action_id'],PROFILE_ACTION)
