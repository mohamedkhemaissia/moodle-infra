class RecoveryStorageError(RuntimeError):
    pass


class RecoveryConflict(ValueError):
    pass


class RecoveryNotFound(ValueError):
    pass


def identifier(value, length=32):
    if not isinstance(value, str) or not re.fullmatch("[0-9a-f]{" + str(length) + "}", value):
        raise ValueError("Reference complete invalide.")
    return value


def note(value):
    if not isinstance(value, str) or not 15 <= len(value.strip()) <= 500 or any(ord(c) < 32 or ord(c) == 127 for c in value):
        raise ValueError("Motif requis : 15 a 500 caracteres sans caractere de controle.")
    return value.strip()


def encoded(value):
    return datetime.fromtimestamp(value, timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def public_request(row, now):
    until = row["valid_until"]
    return {"id": row["id"], "scope": row["scope"], "snapshot_id": row["snapshot_id"],
        "target": row["target"], "reason": row["reason"], "status": row["status"], "revision": row["revision"],
        "requested_by": {"id": row["actor_id"], "username": row["actor_name"]},
        "created_at": encoded(row["created_at"]), "updated_at": encoded(row["updated_at"]),
        "selection": json.loads(row["selected_json"]),
        "decision": None if row["decision_at"] is None else {
            "by": {"id": row["decision_actor_id"], "username": row["decision_actor_name"]},
            "reason": row["decision_reason"], "at": encoded(row["decision_at"]),
            "valid_until": None if until is None else encoded(until),
            "approval_valid": row["status"] == "approved" and row["decision_at"] <= now < until},
        "execution": {"enabled": False, "status": "not_dispatched"}}


def authorize(cursor, principal, now):
    """Bloquer une session revoquee entre le middleware et la transaction metier."""
    if not isinstance(principal, dict) or principal.get("kind") != "human":
        raise AuthDenied("Une session administrateur est requise.")
    user = principal.get("user", {})
    session = principal.get("session_hash")
    if type(user.get("id")) is not int or not isinstance(session, str) or not re.fullmatch("[0-9a-f]{64}", session):
        raise AuthDenied("Une session administrateur est requise.")
    row = cursor.execute("""SELECT u.id,u.username,u.active,u.role,u.version,s.user_version,
        s.created_at,s.last_seen_at,s.expires_at FROM pilotage_auth.users u
        JOIN pilotage_auth.sessions s ON s.user_id=u.id WHERE u.id=%s AND s.token_hash=%s
        FOR SHARE OF u,s""", (user["id"], session)).fetchone()
    if (row is None or not row["active"] or row["role"] != "admin"
            or row["version"] != row["user_version"] or row["version"] != principal.get("version")
            or not row["created_at"] <= row["last_seen_at"] <= now < row["expires_at"]
            or now - row["last_seen_at"] >= IDLE_SECONDS):
        raise AuthDenied("La session administrateur n'est plus valide.")
    return row


class RecoveryStore:
    def __init__(self, *, database_config=None, selector=None):
        try:
            self.config = load_config(database_config)
        except sqlite3.Error:
            raise RecoveryStorageError("Configuration des demandes indisponible.") from None
        if self.config is None:
            raise RecoveryStorageError("PostgreSQL est requis pour les demandes de restauration.")
        self.selector = selector

    @staticmethod
    def check_schema(connection):
        if connection.execute("SELECT version,application_id FROM schema_info WHERE id=1").fetchone() != (1, APPLICATION_ID):
            raise RecoveryStorageError("Schema des demandes incompatible.")

    @contextmanager
    def connection(self, *, write=False):
        import psycopg
        from psycopg.rows import dict_row
        try:
            with raw_connect(self.config, read_only=not write) as connection:
                with connection.transaction():
                    if write:
                        connection.execute("SELECT pg_advisory_xact_lock(%s,0)", (APPLICATION_ID,))
                    else:
                        connection.execute("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ, READ ONLY")
                    connection.execute("SET LOCAL search_path TO pilotage_recovery, pg_catalog")
                    self.check_schema(connection)
                    with connection.cursor(row_factory=dict_row) as cursor:
                        yield cursor
        except (sqlite3.Error, psycopg.Error):
            raise RecoveryStorageError("Stockage des demandes indisponible.") from None

    def initialize(self):
        import psycopg
        try:
            with raw_connect(self.config) as connection:
                with connection.transaction():
                    connection.execute("SELECT pg_advisory_xact_lock(%s,0)", (APPLICATION_ID,))
                    if connection.execute("SELECT to_regnamespace(%s)", (SCHEMA,)).fetchone()[0] is not None:
                        connection.execute("SET LOCAL search_path TO pilotage_recovery, pg_catalog")
                        self.check_schema(connection)
                        return False
                    auth = connection.execute("SELECT version,application_id FROM pilotage_auth.schema_info WHERE id=1").fetchone()
                    if auth != (1, 0x4D4F4155):
                        raise RecoveryStorageError("Initialiser les comptes avant les demandes.")
                    connection.execute("CREATE SCHEMA pilotage_recovery")
                    connection.execute("SET LOCAL search_path TO pilotage_recovery, pg_catalog")
                    for statement in DDL:
                        connection.execute(statement)
                    connection.execute("INSERT INTO schema_info VALUES(1,1,%s)", (APPLICATION_ID,))
                    return True
        except (sqlite3.Error, psycopg.Error):
            raise RecoveryStorageError("Initialisation des demandes indisponible.") from None

    def check(self):
        with self.connection() as cursor:
            cursor.execute("SELECT 1")

    def select(self, scope, snapshot, now):
        if self.selector is None:
            raise RecoveryConflict("Le catalogue n'est pas configure.")
        try:
            return self.selector(scope, snapshot, datetime.fromtimestamp(now, timezone.utc))
        except ValueError as exc:
            raise RecoveryConflict(str(exc)) from None

    def public(self, cursor, row, now):
        return public_request(row, now)

    def transition_guard(self, cursor, row, actor, action, reason, now):
        pass

    def detail_extra(self, cursor, row, now):
        return {}

    @staticmethod
    def event(cursor, row, actor, action, now, evidence):
        cursor.execute("""INSERT INTO events(request_id,actor_id,actor_name,action,observed_at,revision,evidence_json)
            VALUES(%s,%s,%s,%s,%s,%s,%s)""", (row["id"], actor["id"], actor["username"], action, now,
            row["revision"], json.dumps(evidence, sort_keys=True, separators=(",", ":"))))

    def create(self, principal, *, scope, snapshot_id, reason, client_key, now=None):
        now, reason = timestamp(now), note(reason)
        identifier(snapshot_id, 64); identifier(client_key)
        if scope not in ("moodle", "pilotage"):
            raise ValueError("Perimetre invalide.")
        digest = hashlib.sha256(json.dumps([scope, snapshot_id, reason, "isolated_test"], separators=(",", ":")).encode()).hexdigest()
        with self.connection(write=True) as cursor:
            actor = authorize(cursor, principal, now)
            old = cursor.execute("SELECT * FROM requests WHERE actor_id=%s AND client_key=%s", (actor["id"], client_key)).fetchone()
            if old is not None:
                if old["payload_sha256"] != digest:
                    raise RecoveryConflict("Cette reference de demande a deja un contenu different.")
                return self.public(cursor, old, now), False
            selection = self.select(scope, snapshot_id, now)
            row = cursor.execute("""INSERT INTO requests(id,scope,snapshot_id,target,reason,actor_id,actor_name,
                client_key,payload_sha256,status,revision,created_at,updated_at,selected_json)
                VALUES(%s,%s,%s,'isolated_test',%s,%s,%s,%s,%s,'pending',1,%s,%s,%s) RETURNING *""",
                (uuid.uuid4().hex, scope, snapshot_id, reason, actor["id"], actor["username"], client_key, digest,
                now, now, json.dumps(selection, sort_keys=True, separators=(",", ":")))).fetchone()
            self.event(cursor, row, actor, "created", now, selection)
            return self.public(cursor, row, now), True

    def transition(self, principal, request_id, *, action, revision, reason, confirmed_snapshot_id=None, now=None):
        identifier(request_id)
        now, reason = timestamp(now), note(reason)
        if action not in ("approve", "reject", "cancel") or type(revision) is not int or revision < 1:
            raise ValueError("Decision invalide.")
        if action == "approve":
            identifier(confirmed_snapshot_id, 64)
        elif confirmed_snapshot_id is not None:
            raise ValueError("Confirmation inattendue.")
        status = {"approve": "approved", "reject": "rejected", "cancel": "cancelled"}[action]
        with self.connection(write=True) as cursor:
            actor = authorize(cursor, principal, now)
            row = cursor.execute("SELECT * FROM requests WHERE id=%s FOR UPDATE", (request_id,)).fetchone()
            if row is None:
                raise RecoveryNotFound("Demande inconnue.")
            if now < row["updated_at"]:
                raise RecoveryConflict("L'horloge est incoherente ; aucune decision enregistree.")
            if action == "approve" and confirmed_snapshot_id != row["snapshot_id"]:
                raise RecoveryConflict("La confirmation ne correspond pas au point choisi.")
            if (row["status"] == status and row["revision"] == revision + 1
                    and row["decision_actor_id"] == actor["id"] and row["decision_reason"] == reason):
                return self.public(cursor, row, now)
            if row["revision"] != revision or row["status"] not in (("pending", "approved") if action == "cancel" else ("pending",)):
                raise RecoveryConflict("La demande a change ; actualiser avant de decider.")
            self.transition_guard(cursor, row, actor, action, reason, now)
            approval = None
            if action == "approve":
                approval = self.select(row["scope"], row["snapshot_id"], now)
                original = json.loads(row["selected_json"])["point"]
                if any(approval["point"][key] != original[key] for key in ("id", "archived_at", "hostname")):
                    raise RecoveryConflict("Les preuves du point choisi ont change.")
                approval["approver_version"] = actor["version"]
            until = now + APPROVAL_SECONDS if action == "approve" else None
            updated = cursor.execute("""UPDATE requests SET status=%s,revision=revision+1,updated_at=%s,
                decision_actor_id=%s,decision_actor_name=%s,decision_reason=%s,decision_at=%s,valid_until=%s,
                approval_json=%s WHERE id=%s RETURNING *""", (status, now, actor["id"], actor["username"], reason,
                now, until, None if approval is None else json.dumps(approval, sort_keys=True), request_id)).fetchone()
            self.event(cursor, updated, actor, status, now, {"reason": reason, "selection": approval,
                "valid_until": None if until is None else encoded(until), "execution_enabled": False})
            return self.public(cursor, updated, now)

    def listing(self, *, status=None, limit=10, offset=0, now=None):
        now = timestamp(now)
        if status not in (None, *STATES) or type(limit) is not int or not 1 <= limit <= 50 or type(offset) is not int or not 0 <= offset <= 10000:
            raise ValueError("Pagination invalide.")
        with self.connection() as cursor:
            where, args = ("", ()) if status is None else (" WHERE status=%s", (status,))
            total = cursor.execute("SELECT count(*) AS total FROM requests" + where, args).fetchone()["total"]
            rows = cursor.execute("SELECT * FROM requests" + where + " ORDER BY created_at DESC,id LIMIT %s OFFSET %s", (*args, limit, offset)).fetchall()
            return {"items": [self.public(cursor, row, now) for row in rows], "total": total, "limit": limit,
                    "offset": offset, "has_more": offset + limit < total}

    def detail(self, request_id, *, now=None):
        identifier(request_id); now = timestamp(now)
        with self.connection() as cursor:
            row = cursor.execute("SELECT * FROM requests WHERE id=%s", (request_id,)).fetchone()
            if row is None:
                raise RecoveryNotFound("Demande inconnue.")
            events = cursor.execute("SELECT * FROM events WHERE request_id=%s ORDER BY id DESC LIMIT 100", (request_id,)).fetchall()
            return {"request": self.public(cursor, row, now), "events": [{"id": item["id"], "action": item["action"],
                "by": {"id": item["actor_id"], "username": item["actor_name"]}, "at": encoded(item["observed_at"]),
                "revision": item["revision"], "evidence": json.loads(item["evidence_json"])} for item in reversed(events)],
                **self.detail_extra(cursor, row, now)}
