SCHEMA = "pilotage_policy"
APPLICATION_ID = 0x4D504F4C
ACTION = "start_php_stopped"
MODES = ("observation", "assisted", "automatic")
DDL = (
    "CREATE TABLE schema_info(id INTEGER PRIMARY KEY CHECK(id=1),version INTEGER NOT NULL,application_id INTEGER NOT NULL)",
    """CREATE TABLE settings(id INTEGER PRIMARY KEY CHECK(id=1),revision INTEGER NOT NULL CHECK(revision>=1),
        mode TEXT NOT NULL CHECK(mode IN ('observation','assisted','automatic')),
        suspended BOOLEAN NOT NULL,evaluation_context BOOLEAN NOT NULL,
        updated_at DOUBLE PRECISION NOT NULL,actor_id BIGINT REFERENCES pilotage_auth.users(id),actor_name TEXT NOT NULL,
        reason TEXT NOT NULL,sha256 TEXT NOT NULL)""",
    """CREATE TABLE events(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        actor_id BIGINT REFERENCES pilotage_auth.users(id),actor_name TEXT NOT NULL,action TEXT NOT NULL,
        observed_at DOUBLE PRECISION NOT NULL,revision INTEGER NOT NULL,details_json TEXT NOT NULL)""",
    """CREATE TABLE approvals(id TEXT PRIMARY KEY,incident_id BIGINT NOT NULL,action_id TEXT NOT NULL,
        revision INTEGER NOT NULL,context TEXT NOT NULL,actor_id BIGINT NOT NULL REFERENCES pilotage_auth.users(id),actor_version INTEGER NOT NULL,
        actor_name TEXT NOT NULL,reason TEXT NOT NULL,created_at DOUBLE PRECISION NOT NULL,
        valid_until DOUBLE PRECISION NOT NULL,client_key TEXT NOT NULL UNIQUE,payload_sha256 TEXT NOT NULL,
        decision_json TEXT NOT NULL,used_by TEXT)""",
    """CREATE TABLE authorizations(run_id TEXT PRIMARY KEY,incident_id BIGINT NOT NULL UNIQUE,
        revision INTEGER NOT NULL,trigger_mode TEXT NOT NULL,approval_id TEXT REFERENCES approvals(id),
        authorized_at DOUBLE PRECISION NOT NULL,decision_json TEXT NOT NULL,policy_json TEXT NOT NULL)""",
    """CREATE TABLE worker_attempts(incident_id BIGINT NOT NULL,revision INTEGER NOT NULL,
        reserved_at DOUBLE PRECISION NOT NULL,PRIMARY KEY(incident_id,revision))""",
    """CREATE TABLE worker_state(id INTEGER PRIMARY KEY CHECK(id=1),observed_at DOUBLE PRECISION NOT NULL,
        status TEXT NOT NULL,run_id TEXT,reason TEXT)""",
)


class PolicyStorageError(RuntimeError):
    pass


class PolicyConflict(ValueError):
    pass


class PolicyBlocked(ValueError):
    pass


def digest(value):
    return hashlib.sha256(json.dumps(value,sort_keys=True,separators=(",",":"),allow_nan=False).encode()).hexdigest()


def iso(value):
    return datetime.fromtimestamp(timestamp(value),timezone.utc).isoformat(timespec="seconds").replace("+00:00","Z")


def reference(value, length=32):
    if not isinstance(value,str) or not re.fullmatch("[0-9a-f]{"+str(length)+"}",value):
        raise ValueError("Reference complete invalide.")
    return value


def version(value):
    if type(value) is not int or not 1 <= value < 2147483647:
        raise ValueError("Revision invalide.")
    return value


def policy_fields(row):
    return {key:row[key] for key in ("revision","mode","suspended","evaluation_context")}


def validate_policy(row):
    value=policy_fields(row)
    version(value["revision"])
    if value["mode"] not in MODES or any(type(value[k]) is not bool for k in ("suspended","evaluation_context")):
        raise PolicyStorageError("Politique incompatible.")
    if row["sha256"] != digest(value):
        raise PolicyStorageError("Empreinte de politique incompatible.")
    return value


def public_policy(row):
    value=validate_policy(row)
    return {**value,"sha256":row["sha256"],"updated_at":iso(row["updated_at"]),
            "updated_by":row["actor_name"],"reason":row["reason"]}


def admission(policy, *, automatic=False, now=None):
    # Type/digest checks precede every gate, including writes made outside the API.
    validate_policy(policy)
    updated=policy["updated_at"]
    if isinstance(updated,str): updated=datetime.fromisoformat(updated.replace("Z","+00:00")).timestamp()
    if timestamp(now) < timestamp(updated): raise PolicyBlocked("policy_clock_inconsistent")
    if policy["suspended"]:
        raise PolicyBlocked("policy_suspended")
    if policy["mode"] == "observation":
        raise PolicyBlocked("observation_mode")
    if automatic and policy["mode"] != "automatic":
        raise PolicyBlocked("automatic_mode_not_active")


def decision_reference(document, incident_id, now):
    try:
        d=document["decision"]
        if (type(incident_id) is not int or not 1 <= incident_id <= 9223372036854775807
                or document["status"] != "available" or document["snapshot_usable"] is not True
                or d["incident_id"] != incident_id or d["signal_key"] != "moodle_https"
                or d["status"] != "recommendation" or d["incident_status"] != "open"
                or d["latest_state"] != "triggered" or d["evidence"].get("probe_success") is not False
                or d["recommended_action"]["id"] != "diagnose_moodle_https"):
            raise ValueError("signal")
        for key in ("input_evaluated_at","valid_until"):
            parsed=datetime.fromisoformat(d[key].replace("Z","+00:00"))
            if parsed.tzinfo is None:
                raise ValueError("date")
            if key == "input_evaluated_at": start=timestamp(parsed.timestamp())
            else: expiry=timestamp(parsed.timestamp())
        if not start <= now < expiry or not 0 < expiry-start <= 90:
            raise ValueError("expiry")
        reference(d["decision_id"],64); reference(d["policy_sha256"],64)
        if not isinstance(d["context"],str) or not 1 <= len(d["context"]) <= 200:
            raise ValueError("context")
        encoded=json.dumps(document,sort_keys=True,separators=(",",":"),allow_nan=False)
        if len(encoded.encode()) > 131072:
            raise ValueError("size")
        return d,expiry,encoded
    except (ValueError,KeyError,TypeError,OverflowError,AttributeError):
        raise PolicyBlocked("recent_confirmed_moodle_decision_required") from None


class PolicyStore:
    def __init__(self, *, database_config=None):
        try: self.config=load_config(database_config)
        except sqlite3.Error: raise PolicyStorageError("Configuration des politiques indisponible.") from None
        if self.config is None: raise PolicyStorageError("PostgreSQL est requis pour les politiques.")

    @staticmethod
    def check_schema(connection):
        if connection.execute("SELECT version,application_id FROM schema_info WHERE id=1").fetchone() != (1,APPLICATION_ID):
            raise PolicyStorageError("Schema des politiques incompatible.")

    @contextmanager
    def connection(self, *, write=False):
        import psycopg
        from psycopg.rows import dict_row
        try:
            with raw_connect(self.config,read_only=not write) as connection:
                with connection.transaction():
                    if write: connection.execute("SELECT pg_advisory_xact_lock(%s,0)",(APPLICATION_ID,))
                    else: connection.execute("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ, READ ONLY")
                    connection.execute("SET LOCAL search_path TO pilotage_policy, pg_catalog")
                    self.check_schema(connection)
                    with connection.cursor(row_factory=dict_row) as cursor: yield cursor
        except (sqlite3.Error,psycopg.Error):
            raise PolicyStorageError("Stockage des politiques indisponible.") from None

    def initialize(self):
        import psycopg
        try:
            with raw_connect(self.config) as connection:
                with connection.transaction():
                    connection.execute("SELECT pg_advisory_xact_lock(%s,0)",(APPLICATION_ID,))
                    if connection.execute("SELECT to_regnamespace(%s)",(SCHEMA,)).fetchone()[0] is not None:
                        connection.execute("SET LOCAL search_path TO pilotage_policy, pg_catalog")
                        self.check_schema(connection)
                        return False
                    if connection.execute("SELECT version,application_id FROM pilotage_auth.schema_info WHERE id=1").fetchone() != (1,0x4D4F4155):
                        raise PolicyStorageError("Initialiser les comptes avant les politiques.")
                    connection.execute("CREATE SCHEMA pilotage_policy")
                    connection.execute("SET LOCAL search_path TO pilotage_policy, pg_catalog")
                    for statement in DDL: connection.execute(statement)
                    connection.execute("INSERT INTO schema_info VALUES(1,1,%s)",(APPLICATION_ID,))
                    initial={"revision":1,"mode":"observation","suspended":False,"evaluation_context":False}
                    connection.execute("INSERT INTO settings VALUES(1,1,'observation',false,false,%s,NULL,'initialisation',%s,%s)",
                        (time.time(),"Observer les services avant d'activer une correction.",digest(initial)))
                    return True
        except (sqlite3.Error,psycopg.Error):
            raise PolicyStorageError("Initialisation des politiques indisponible.") from None

    def check(self):
        with self.connection() as cursor: public_policy(self.row(cursor))

    @staticmethod
    def row(cursor):
        row=cursor.execute("SELECT * FROM settings WHERE id=1").fetchone()
        if row is None: raise PolicyStorageError("Politique absente.")
        public_policy(row)
        return row

    @staticmethod
    def event(cursor, actor, action, row, now, details):
        cursor.execute("INSERT INTO events(actor_id,actor_name,action,observed_at,revision,details_json) VALUES(%s,%s,%s,%s,%s,%s)",
            (actor.get("id"),actor["username"],action,now,row["revision"],json.dumps(details,sort_keys=True,allow_nan=False)))

    def view(self, *, now=None):
        with self.connection() as cursor:
            now=timestamp(now); row=self.row(cursor)
            worker=cursor.execute("SELECT * FROM worker_state WHERE id=1").fetchone()
            status="unknown" if worker is None else "stale" if not 0 <= now-worker["observed_at"] <= 90 else worker["status"]
            return {"status":"available","evaluated_at":iso(now),"policy":public_policy(row),
                "allowed_actions":[ACTION],"worker":{"status":status,"last_checked_at":iso(worker["observed_at"]) if worker else None,
                    "run_id":worker["run_id"] if worker else None},
                "semantics":{"observation":"Mesures et diagnostics ; aucune correction.",
                    "assisted":"Correction lancee manuellement sur le serveur.",
                    "automatic":"Le worker peut demarrer PHP confirme arrete ; aucune autre correction automatique.",
                    "evaluation":"Approbation humaine de l'incident requise avant toute correction pendant une evaluation.",
                    "suspension":"Bloque les nouvelles autorisations ; une action deja autorisee peut finir sa verification."}}

    def update(self, principal, *, revision, mode, suspended, evaluation_context, reason, confirm_automatic=False, now=None):
        version(revision); reason=note(reason)
        if mode not in MODES or any(type(v) is not bool for v in (suspended,evaluation_context,confirm_automatic)):
            raise ValueError("Politique invalide.")
        if mode == "automatic" and not confirm_automatic: raise ValueError("Confirmer explicitement le mode automatique.")
        with self.connection(write=True) as cursor:
            now=timestamp(now); actor=authorize(cursor,principal,now); before=self.row(cursor)
            if before["revision"] != revision: raise PolicyConflict("Politique modifiee : actualiser avant d'enregistrer.")
            if now < before["updated_at"]: raise PolicyBlocked("policy_clock_inconsistent")
            requested={"mode":mode,"suspended":suspended,"evaluation_context":evaluation_context}
            if all(before[k] == v for k,v in requested.items()): return public_policy(before),False
            after={"revision":revision+1,**requested}
            row=cursor.execute("""UPDATE settings SET revision=%s,mode=%s,suspended=%s,evaluation_context=%s,
                updated_at=%s,actor_id=%s,actor_name=%s,reason=%s,sha256=%s WHERE id=1 RETURNING *""",
                (after["revision"],mode,suspended,evaluation_context,now,actor["id"],actor["username"],reason,digest(after))).fetchone()
            self.event(cursor,actor,"policy_updated",row,now,{"before":public_policy(before),"after":public_policy(row)})
            return public_policy(row),True

    def history(self, *, limit=10, offset=0):
        if type(limit) is not int or not 1 <= limit <= 50 or type(offset) is not int or not 0 <= offset <= 10000:
            raise ValueError("Pagination invalide.")
        with self.connection() as cursor:
            total=cursor.execute("SELECT count(*) AS total FROM events").fetchone()["total"]
            rows=cursor.execute("SELECT * FROM events ORDER BY id DESC LIMIT %s OFFSET %s",(limit,offset)).fetchall()
            return {"items":[{"id":r["id"],"action":r["action"],"actor":r["actor_name"],"at":iso(r["observed_at"]),
                "revision":r["revision"],"details":json.loads(r["details_json"])} for r in rows],
                "total":total,"limit":limit,"offset":offset,"has_more":offset+len(rows)<total}

    def approve(self, principal, document, *, incident_id, revision, reason, client_key, now=None):
        version(revision); reason=note(reason); reference(client_key)
        payload=digest([incident_id,revision,reason])
        with self.connection(write=True) as cursor:
            now=timestamp(now); actor=authorize(cursor,principal,now); row=self.row(cursor)
            if revision != row["revision"]: raise PolicyConflict("Politique modifiee : actualiser.")
            admission(row,now=now)
            if not row["evaluation_context"]: raise PolicyConflict("Le contexte d'evaluation n'est pas actif.")
            old=cursor.execute("SELECT * FROM approvals WHERE client_key=%s",(client_key,)).fetchone()
            if old:
                if old["payload_sha256"] != payload or old["actor_id"] != actor["id"]:
                    raise PolicyConflict("Reference deja utilisee pour une autre approbation.")
                return self.approval_public(old,now),False
            d,expiry,encoded=decision_reference(document,incident_id,now)
            approval=cursor.execute("""INSERT INTO approvals VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,NULL) RETURNING *""",
                (uuid.uuid4().hex,incident_id,ACTION,revision,d["context"],actor["id"],actor["version"],actor["username"],reason,now,expiry,client_key,payload,encoded)).fetchone()
            self.event(cursor,actor,"action_approved",row,now,{"approval_id":approval["id"],"incident_id":incident_id,
                "action_id":ACTION,"reason":reason,"decision_id":d["decision_id"],"valid_until":iso(expiry)})
            return self.approval_public(approval,now),True

    @staticmethod
    def approval_public(row, now):
        return {"id":row["id"],"incident_id":row["incident_id"],"action_id":row["action_id"],"revision":row["revision"],
            "by":row["actor_name"],"reason":row["reason"],"valid_until":iso(row["valid_until"]),
            "used_by":row["used_by"],"valid":row["used_by"] is None and row["created_at"] <= now < row["valid_until"]}

    @staticmethod
    def approval(cursor, row, d, now):
        if not row["evaluation_context"]: return None
        approval=cursor.execute("""SELECT a.* FROM approvals a JOIN pilotage_auth.users u ON u.id=a.actor_id
            WHERE a.incident_id=%s AND a.action_id=%s AND a.revision=%s AND a.context=%s AND a.used_by IS NULL
            AND a.created_at<=%s AND a.valid_until>%s AND u.active AND u.role='admin' AND u.version=a.actor_version
            ORDER BY a.created_at DESC LIMIT 1 FOR SHARE OF u""",
            (d["incident_id"],ACTION,row["revision"],d["context"],now,now)).fetchone()
        if approval is None: raise PolicyBlocked("evaluation_approval_required")
        return approval

    def reserve_worker(self, document, *, now=None):
        with self.connection(write=True) as cursor:
            now=timestamp(now); row=self.row(cursor); admission(row,automatic=True,now=now)
            d,_,_=decision_reference(document,document.get("decision",{}).get("incident_id"),now)
            self.approval(cursor,row,d,now)
            if cursor.execute("SELECT 1 FROM authorizations WHERE incident_id=%s",(d["incident_id"],)).fetchone():
                return None
            made=cursor.execute("INSERT INTO worker_attempts VALUES(%s,%s,%s) ON CONFLICT DO NOTHING RETURNING incident_id",
                (d["incident_id"],row["revision"],now)).fetchone()
            return public_policy(row) if made else None

    def dispatch(self, decision, expected_policy, *, run_id, automatic, reserve, now=None):
        reference(run_id)
        fixed_now=now
        with self.connection(write=True) as cursor:
            now=timestamp(now); row=self.row(cursor); admission(row,automatic=automatic,now=now)
            if not isinstance(expected_policy,dict) or (expected_policy.get("revision"),expected_policy.get("sha256")) != (row["revision"],row["sha256"]):
                raise PolicyBlocked("operating_policy_changed")
            d,expiry,encoded=decision_reference(decision,decision.get("decision",{}).get("incident_id"),now)
            approval=self.approval(cursor,row,d,now)
            if cursor.execute("SELECT 1 FROM authorizations WHERE incident_id=%s",(d["incident_id"],)).fetchone():
                raise PolicyBlocked("policy_action_already_authorized")
            # The remediation reservation is durable before this authorization commits.
            reason=reserve()
            if reason: raise PolicyBlocked(reason)
            # Waiting for another store lock must not extend either validity window.
            checked=timestamp(fixed_now)
            if checked < now:
                raise PolicyBlocked("authorization_clock_inconsistent")
            if checked >= expiry or (approval and checked >= approval["valid_until"]):
                raise PolicyBlocked("authorization_expired_before_dispatch")
            policy=public_policy(row)
            cursor.execute("INSERT INTO authorizations VALUES(%s,%s,%s,%s,%s,%s,%s,%s)",
                (run_id,d["incident_id"],row["revision"],"automatic" if automatic else "manual",approval["id"] if approval else None,
                 checked,encoded,json.dumps(policy,sort_keys=True)))
            if approval: cursor.execute("UPDATE approvals SET used_by=%s WHERE id=%s",(run_id,approval["id"]))
            actor={"username":"worker_automatique" if automatic else "commande_locale"}
            self.event(cursor,actor,"action_authorized",row,checked,{"run_id":run_id,"incident_id":d["incident_id"],
                "action_id":ACTION,"approval_id":approval["id"] if approval else None,"decision_id":d["decision_id"]})
            return {"policy":policy,"approval_id":approval["id"] if approval else None,"authorized_at":iso(checked),
                "trigger_mode":"automatic" if automatic else "manual"}

    def heartbeat(self, status, *, run_id=None, reason=None, now=None):
        if status not in ("idle","running","error") or (run_id is not None and not re.fullmatch("[0-9a-f]{32}",run_id)):
            raise ValueError("Etat du worker invalide.")
        with self.connection(write=True) as cursor:
            cursor.execute("INSERT INTO worker_state VALUES(1,%s,%s,%s,%s) ON CONFLICT(id) DO UPDATE SET observed_at=excluded.observed_at,status=excluded.status,run_id=excluded.run_id,reason=excluded.reason",
                (timestamp(now),status,run_id,str(reason)[:120] if reason else None))
