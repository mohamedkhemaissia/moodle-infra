def result_document(value):
    """Projection stricte : aucune sortie de commande, configuration ou secret."""
    if not isinstance(value, dict) or value.get('production_changed') is not False:
        raise ValueError('Preuve du test invalide.')
    if value.get('status') not in ('restore_validated', 'failed', 'blocked', 'inconclusive'):
        raise ValueError('Resultat du test invalide.')
    result = {key: value[key] for key in ('status', 'production_changed')}
    reason = value.get('reason')
    if reason is not None:
        if not isinstance(reason, str) or not re.fullmatch('[a-z][a-z0-9_]{0,95}', reason):
            raise ValueError('Code du resultat invalide.')
        result['reason'] = reason
    cleanup = value.get('cleanup')
    if (not isinstance(cleanup, dict) or set(cleanup) != {'containers_removed','networks_removed','temporary_files_removed'}
            or any(type(v) is not bool for v in cleanup.values())):
        raise ValueError('Preuve du nettoyage invalide.')
    result['cleanup'] = cleanup
    for key in ('files_verified', 'tables_verified', 'rows_verified', 'courses', 'users', 'quizzes'):
        if key in value:
            if type(value[key]) is not int or not 0 <= value[key] <= 10**12:
                raise ValueError('Comptage du test invalide.')
            result[key] = value[key]
    for key in ('inventory_sha256',):
        if key in value:
            identifier(value[key], 64); result[key] = value[key]
    for key in ('database_check', 'login_check', 'sequence_check', 'archive_check'):
        if key in value:
            if value[key] != 'passed': raise ValueError('Verification du test invalide.')
            result[key] = value[key]
    if value['status'] == 'restore_validated' and (not all(cleanup.values()) or value.get('database_check') != 'passed'):
        raise ValueError('Succes sans preuve complete.')
    if 'runner_status' in value:
        if value['runner_status'] not in ('successful','failed','timeout','canceled'):raise ValueError('Etat Runner invalide.')
        result['runner_status']=value['runner_status']
    if 'runner_rc' in value:
        if type(value['runner_rc']) is not int or not -255<=value['runner_rc']<=255:raise ValueError('Retour Runner invalide.')
        result['runner_rc']=value['runner_rc']
    return result


def public_execution(row):
    if row is None:
        return {'enabled': True, 'status': 'not_dispatched'}
    return {'enabled': True, 'status': row['status'], 'id': row['id'],
        'queued_at': encoded(row['queued_at']),
        'started_at': None if row['started_at'] is None else encoded(row['started_at']),
        'finished_at': None if row['finished_at'] is None else encoded(row['finished_at']),
        'reason_code': row['reason_code'],
        'report': None if row['report_json'] is None else json.loads(row['report_json'])}


class RecoveryExecutionStore(RecoveryStore):
    execution_enabled = True

    def initialize_execution(self):
        import psycopg
        try:
            with raw_connect(self.config) as connection:
                with connection.transaction():
                    connection.execute('SELECT pg_advisory_xact_lock(%s,0)', (APPLICATION_ID,))
                    connection.execute('SET LOCAL search_path TO pilotage_recovery, pg_catalog')
                    self.check_schema(connection)
                    present = [connection.execute('SELECT to_regclass(%s)', ('pilotage_recovery.'+name,)).fetchone()[0]
                               for name in ('executions','execution_events')]
                    if any(present):
                        if not all(present): raise RecoveryStorageError('Journal d execution incomplet.')
                        return False
                    for statement in DDL: connection.execute(statement)
                    return True
        except (sqlite3.Error, psycopg.Error):
            raise RecoveryStorageError('Initialisation des executions indisponible.') from None

    def check(self):
        with self.connection() as cursor:
            cursor.execute('SELECT id,status,claim_token FROM executions LIMIT 0')
            cursor.execute('SELECT id,execution_id,revision FROM execution_events LIMIT 0')

    def public(self, cursor, row, now):
        value = public_request(row, now)
        execution = cursor.execute('SELECT * FROM executions WHERE request_id=%s', (row['id'],)).fetchone()
        value['execution'] = public_execution(execution)
        return value

    @staticmethod
    def execution_event(cursor, row, action, now, evidence, actor=None):
        cursor.execute('''INSERT INTO execution_events(execution_id,actor_id,actor_name,action,observed_at,revision,evidence_json)
            VALUES(%s,%s,%s,%s,%s,%s,%s)''', (row['id'], None if actor is None else actor['id'],
            'worker' if actor is None else actor['username'], action, now, row['revision'], json.dumps(evidence,sort_keys=True)))

    def detail_extra(self, cursor, row, now):
        events = cursor.execute('''SELECT e.* FROM execution_events e JOIN executions x ON e.execution_id=x.id
            WHERE x.request_id=%s ORDER BY e.id LIMIT 100''', (row['id'],)).fetchall()
        return {'execution_events': [{'id':e['id'], 'action':e['action'], 'at':encoded(e['observed_at']),
            'by':{'id':e['actor_id'], 'username':e['actor_name'], 'kind':'worker' if e['actor_id'] is None else 'human'},
            'evidence':json.loads(e['evidence_json'])} for e in events]}

    def transition_guard(self, cursor, row, actor, action, reason, now):
        execution = cursor.execute('SELECT * FROM executions WHERE request_id=%s FOR UPDATE', (row['id'],)).fetchone()
        if execution is None: return
        if action != 'cancel' or execution['status'] != 'queued':
            raise RecoveryConflict('Un test a deja ete pris en charge ; sa preuve doit etre conservee.')
        execution = cursor.execute("""UPDATE executions SET status='cancelled',revision=revision+1,updated_at=%s,
            finished_at=%s,reason_code='cancelled_before_start' WHERE id=%s RETURNING *""", (now,now,execution['id'])).fetchone()
        self.execution_event(cursor,execution,'cancelled',now,{'reason':reason},actor)

    def approval(self, cursor, request, now, version=None):
        if (request['status'] != 'approved' or request['valid_until'] is None
                or not request['decision_at'] <= now < request['valid_until']):
            raise RecoveryConflict('Approbation absente ou expiree ; creer une nouvelle demande.')
        proof = json.loads(request['approval_json'])
        recorded_version = proof.get('approver_version')
        if type(recorded_version) is not int or (version is not None and version != recorded_version):
            raise RecoveryConflict('Approbation anterieure a l execution ; creer une nouvelle demande.')
        approver = cursor.execute('SELECT active,role,version FROM pilotage_auth.users WHERE id=%s FOR SHARE',
                                 (request['decision_actor_id'],)).fetchone()
        if not approver or not approver['active'] or approver['role'] != 'admin' or approver['version'] != recorded_version:
            raise RecoveryConflict('L approbateur n est plus autorise.')
        selection = self.select(request['scope'], request['snapshot_id'], now)
        if any(selection['point'][key] != proof['point'][key] for key in ('id','archived_at','hostname')):
            raise RecoveryConflict('Les preuves du point approuve ont change.')
        return recorded_version

    def enqueue(self, principal, request_id, *, revision, confirmed_snapshot_id, now=None):
        identifier(request_id); identifier(confirmed_snapshot_id,64); now=timestamp(now)
        if type(revision) is not int or revision < 1: raise ValueError('Revision invalide.')
        with self.connection(write=True) as cursor:
            actor = authorize(cursor,principal,now)
            request = cursor.execute('SELECT * FROM requests WHERE id=%s FOR UPDATE',(request_id,)).fetchone()
            if request is None: raise RecoveryNotFound('Demande inconnue.')
            if request['snapshot_id'] != confirmed_snapshot_id or request['revision'] != revision or now < request['updated_at']:
                raise RecoveryConflict('Confirmation ou revision incompatible ; actualiser la demande.')
            old = cursor.execute('SELECT * FROM executions WHERE request_id=%s',(request_id,)).fetchone()
            if old is not None:
                # Un clic repete ne cree jamais un second essai, meme apres expiration.
                return self.public(cursor,request,now),False
            approver_version = self.approval(cursor,request,now)
            credential = {'kind':'human','user':{'id':actor['id']},'version':principal['version'],
                          'session_hash':principal['session_hash']}
            row = cursor.execute('''INSERT INTO executions(id,request_id,scope,snapshot_id,status,actor_id,actor_name,
                credential_json,approver_version,queued_at,updated_at) VALUES(%s,%s,%s,%s,'queued',%s,%s,%s,%s,%s,%s) RETURNING *''',
                (uuid.uuid4().hex,request_id,request['scope'],request['snapshot_id'],actor['id'],actor['username'],
                 json.dumps(credential,sort_keys=True),approver_version,now,now)).fetchone()
            self.execution_event(cursor,row,'queued',now,{'snapshot_id':request['snapshot_id'],'target':'isolated_test'},actor)
            return self.public(cursor,request,now),True

    def claim(self, boot_id, *, now=None):
        identifier(boot_id); now=timestamp(now)
        with self.connection(write=True) as cursor:
            if cursor.execute("SELECT id FROM executions WHERE status='running' LIMIT 1").fetchone(): return None
            row=cursor.execute("SELECT * FROM executions WHERE status='queued' ORDER BY queued_at,id LIMIT 1 FOR UPDATE").fetchone()
            if row is None: return None
            request=cursor.execute('SELECT * FROM requests WHERE id=%s FOR UPDATE',(row['request_id'],)).fetchone()
            try:
                if now < row['updated_at']: raise RecoveryConflict('clock')
                authorize(cursor,json.loads(row['credential_json']),now)
                self.approval(cursor,request,now,row['approver_version'])
            except (AuthDenied,RecoveryConflict,ValueError):
                updated=cursor.execute("""UPDATE executions SET status='blocked',revision=revision+1,updated_at=%s,
                    finished_at=%s,reason_code='authorization_or_catalog_unusable',credential_json='{}' WHERE id=%s RETURNING *""",
                    (max(now,row['updated_at']),max(now,row['updated_at']),row['id'])).fetchone()
                self.execution_event(cursor,updated,'blocked',max(now,row['updated_at']),{'reason_code':updated['reason_code']})
                return None
            updated=cursor.execute("""UPDATE executions SET status='running',revision=revision+1,updated_at=%s,
                started_at=%s,deadline_at=%s,boot_id=%s,claim_token=%s WHERE id=%s RETURNING *""",
                (now,now,now+MAX_RUN_SECONDS,boot_id,uuid.uuid4().hex,row['id'])).fetchone()
            self.execution_event(cursor,updated,'started',now,{'target':'isolated_test'})
            return {**dict(updated),'point':json.loads(request['approval_json'])['point']}

    def abandoned(self, boot_id, *, now=None):
        identifier(boot_id); now=timestamp(now)
        with self.connection() as cursor:
            return [dict(row) for row in cursor.execute("""SELECT * FROM executions WHERE status='running'
                AND (boot_id<>%s OR deadline_at<=%s) ORDER BY queued_at LIMIT 1""",(boot_id,now)).fetchall()]

    def cleanup_pending(self):
        with self.connection() as cursor:
            return [dict(row) for row in cursor.execute("""SELECT * FROM executions WHERE status='inconclusive'
                AND report_json IS NOT NULL AND NOT (report_json::jsonb->'cleanup' @> '{"containers_removed":true,"networks_removed":true,"temporary_files_removed":true}'::jsonb)
                ORDER BY queued_at LIMIT 1""").fetchall()]

    def record_cleanup(self, execution_id, flags, *, now=None):
        identifier(execution_id);now=timestamp(now)
        with self.connection(write=True) as cursor:
            row=cursor.execute('SELECT * FROM executions WHERE id=%s FOR UPDATE',(execution_id,)).fetchone()
            if not row or row['status']!='inconclusive':raise RecoveryConflict('Nettoyage non applicable.')
            report=json.loads(row['report_json']);old=report['cleanup'];report['cleanup']=flags
            result_document(report)
            if old==flags:return
            updated=cursor.execute('UPDATE executions SET report_json=%s,revision=revision+1 WHERE id=%s RETURNING *',
                (json.dumps(report,sort_keys=True),execution_id)).fetchone()
            self.execution_event(cursor,updated,'finished',max(now,row['finished_at']),{'cleanup':flags,'status':'inconclusive'})

    def finish(self, execution_id, claim_token, report, *, now=None, interrupted=False):
        identifier(execution_id); identifier(claim_token); now=timestamp(now)
        report=result_document(report)
        with self.connection(write=True) as cursor:
            row=cursor.execute('SELECT * FROM executions WHERE id=%s FOR UPDATE',(execution_id,)).fetchone()
            if row is None: raise RecoveryNotFound('Execution inconnue.')
            if row['status'] != 'running' or row['claim_token'] != claim_token:
                raise RecoveryConflict('L execution a deja un resultat ou une autre prise en charge.')
            if now < row['started_at'] or now > row['deadline_at'] or interrupted:
                report['status']='inconclusive'; report['reason']='execution_interrupted_or_deadline'
            if report['status']=='restore_validated':
                required = ('login_check','archive_check') if row['scope']=='moodle' else ('sequence_check',)
                if any(report.get(key)!='passed' for key in required) or (row['scope']=='pilotage' and ('inventory_sha256' not in report or report.get('tables_verified',0)<16)):
                    raise ValueError('Preuves du perimetre incompletes.')
            state={'restore_validated':'succeeded','failed':'failed','blocked':'blocked','inconclusive':'inconclusive'}[report['status']]
            now=max(now,row['started_at'])
            updated=cursor.execute('''UPDATE executions SET status=%s,revision=revision+1,updated_at=%s,
                finished_at=%s,reason_code=%s,report_json=%s,credential_json='{}' WHERE id=%s RETURNING *''',
                (state,now,now,report.get('reason'),json.dumps(report,sort_keys=True),row['id'])).fetchone()
            self.execution_event(cursor,updated,'interrupted' if interrupted else 'finished',now,
                                 {'status':state,'report':report})
            return public_execution(updated)
