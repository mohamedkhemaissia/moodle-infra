"""Historique des transitions de decision ; seul l'observateur peut l'alimenter.

Schema PostgreSQL additionnel : les journaux d'incidents et leurs migrations
restent au format v1. Une entree conserve les mesures de sa premiere evaluation ;
les confirmations suivantes prolongent sa periode sans remplacer ces preuves.
"""
from datetime import datetime, timezone
import hashlib
import json
import math
import sqlite3
import time

APPLICATION_ID = 0x4D444543
STATUSES = ("recommendation", "blocked", "monitoring", "closed")
SCHEMA = (
    "CREATE SCHEMA pilotage_decisions",
    """CREATE TABLE pilotage_decisions.schema_info (
        id INTEGER PRIMARY KEY CHECK(id=1), version INTEGER NOT NULL CHECK(version=1),
        application_id INTEGER NOT NULL)""",
    """CREATE TABLE pilotage_decisions.entries (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        incident_id BIGINT NOT NULL REFERENCES pilotage_incidents.incidents(id),
        signature TEXT NOT NULL CHECK(length(signature)=64),
        status TEXT NOT NULL CHECK(status IN ('recommendation','blocked','monitoring','closed')),
        first_observed_at DOUBLE PRECISION NOT NULL,
        last_observed_at DOUBLE PRECISION NOT NULL CHECK(last_observed_at>=first_observed_at),
        observations BIGINT NOT NULL CHECK(observations>=1),
        decision_json TEXT NOT NULL, policy_json TEXT NOT NULL, collector_json TEXT NOT NULL)""",
    "CREATE INDEX decision_incident_history ON pilotage_decisions.entries(incident_id,id DESC)",
    "CREATE INDEX decision_status_history ON pilotage_decisions.entries(status,id DESC)",
    """CREATE TABLE pilotage_decisions.state (
        id INTEGER PRIMARY KEY CHECK(id=1), started_at DOUBLE PRECISION NOT NULL,
        last_input_at DOUBLE PRECISION, last_evaluated_at DOUBLE PRECISION)""",
)


def encode(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False)


def iso(value):
    try:
        return None if value is None else datetime.fromtimestamp(value, timezone.utc).isoformat().replace("+00:00", "Z")
    except (OverflowError, ValueError, TypeError, OSError):
        raise sqlite3.DatabaseError("Date du journal incoherente.") from None


def signature(decision):
    # Les mesures et les dates varient a chaque collecte. Une nouvelle preuve de
    # la meme recommandation ne constitue pas une nouvelle transition.
    fields = ("incident_id", "signal_key", "incident_status", "latest_state", "context", "status", "priority",
              "reason_codes", "recommended_action", "policy_version", "policy_sha256")
    return hashlib.sha256(encode({key: decision[key] for key in fields}).encode()).hexdigest()


class DecisionJournal:
    def __init__(self, incident_store):
        if incident_store is None or incident_store.database is None:
            raise ValueError("Le journal des decisions exige le stockage PostgreSQL des incidents.")
        self.store = incident_store

    @staticmethod
    def check(connection):
        row = connection.execute("SELECT version,application_id FROM pilotage_decisions.schema_info WHERE id=1").fetchone()
        if row is None or tuple(row) != (1, APPLICATION_ID):
            raise sqlite3.DatabaseError("Version du journal des decisions incompatible.")
        row = connection.execute("SELECT * FROM pilotage_decisions.state WHERE id=1").fetchone()
        if row is None or (row["last_input_at"] is None) != (row["last_evaluated_at"] is None):
            raise sqlite3.DatabaseError("Couverture du journal absente.")
        for key in ("started_at", "last_input_at", "last_evaluated_at"):
            value = row[key]
            if value is not None and (type(value) not in (int, float) or not math.isfinite(value) or value < 0):
                raise sqlite3.DatabaseError("Couverture du journal incoherente.")

    def initialize(self, *, now=None):
        now = time.time() if now is None else now
        if type(now) not in (int, float) or not math.isfinite(now) or now < 0:
            raise ValueError("Date du journal invalide.")
        with self.store.connection(write=True) as connection:
            connection.execute("BEGIN IMMEDIATE")
            try:
                exists = connection.execute("SELECT to_regnamespace('pilotage_decisions')").fetchone()[0] is not None
                if not exists:
                    for statement in SCHEMA:
                        connection.execute(statement)
                    connection.execute("INSERT INTO pilotage_decisions.schema_info VALUES(1,1,?)", (APPLICATION_ID,))
                    connection.execute("INSERT INTO pilotage_decisions.state(id,started_at) VALUES(1,?)", (now,))
                self.check(connection)
                connection.execute("COMMIT")
                return not exists
            except Exception:
                connection.execute("ROLLBACK")
                raise

    def record(self, connection, document, policy, *, point, completed_at):
        """Appeler dans la transaction qui vient d'enregistrer les incidents."""
        self.check(connection)
        state = connection.execute("SELECT last_input_at FROM pilotage_decisions.state WHERE id=1").fetchone()
        if state[0] is not None and point <= state[0]:
            raise sqlite3.DatabaseError("Evaluation du journal hors ordre.")
        for decision in document["decisions"]:
            fingerprint = signature(decision)
            previous = connection.execute("""SELECT id,signature FROM pilotage_decisions.entries
                WHERE incident_id=? ORDER BY id DESC LIMIT 1""", (decision["incident_id"],)).fetchone()
            if previous is not None and previous["signature"] == fingerprint:
                connection.execute("""UPDATE pilotage_decisions.entries SET last_observed_at=?,observations=observations+1
                    WHERE id=?""", (point, previous["id"]))
            else:
                connection.execute("""INSERT INTO pilotage_decisions.entries
                    (incident_id,signature,status,first_observed_at,last_observed_at,observations,
                     decision_json,policy_json,collector_json) VALUES(?,?,?,?,?,1,?,?,?)""",
                    (decision["incident_id"], fingerprint, decision["status"], point, point,
                     encode(decision), encode(policy), encode(document["collector"])))
        connection.execute("UPDATE pilotage_decisions.state SET last_input_at=?,last_evaluated_at=? WHERE id=1",
                           (point, completed_at))

    @staticmethod
    def entry(row):
        decision, policy, collector = (json.loads(row[key]) for key in ("decision_json", "policy_json", "collector_json"))
        for value in (decision, policy, collector):
            encode(value)
        if (not isinstance(decision, dict) or not isinstance(policy, dict) or not isinstance(collector, dict)
                or decision.get("incident_id") != row["incident_id"] or decision.get("status") != row["status"]
                or signature(decision) != row["signature"]):
            raise sqlite3.DatabaseError("Entree du journal incoherente.")
        return {"id": row["id"], "incident_id": row["incident_id"], "status": row["status"],
                "first_observed_at": iso(row["first_observed_at"]), "last_observed_at": iso(row["last_observed_at"]),
                "observations": row["observations"], "persisted": True,
                "decision": decision, "policy": policy, "collector": collector}

    @staticmethod
    def coverage(connection, now):
        row = connection.execute("SELECT * FROM pilotage_decisions.state WHERE id=1").fetchone()
        input_at, completed = row["last_input_at"], row["last_evaluated_at"]
        age = None if input_at is None or completed is None else now - min(input_at, completed)
        status = ("waiting" if age is None else "clock_inconsistent" if now < max(input_at, completed)
                  else "stale" if age > 90 else "running")
        return {"started_at": iso(row["started_at"]), "last_input_at": iso(input_at),
                "last_evaluated_at": iso(completed), "status": status,
                "input_age_seconds": None if age is None else round(age, 3), "backfilled": False}

    def list(self, now, *, limit=50, before_id=None, status=None, incident_id=None):
        if (type(now) not in (int, float) or not math.isfinite(now) or now < 0
                or type(limit) is not int or not 1 <= limit <= 100 or status not in (None, *STATUSES)
                or any(value is not None and (type(value) is not int or not 1 <= value < 2**63)
                       for value in (before_id, incident_id))):
            raise ValueError("Filtre du journal invalide.")
        clauses, parameters = [], []
        for column, operation, value in (("id", "<", before_id), ("status", "=", status), ("incident_id", "=", incident_id)):
            if value is not None:
                clauses.append(column + operation + "?")
                parameters.append(value)
        where = " WHERE " + " AND ".join(clauses) if clauses else ""
        with self.store.connection() as connection:
            connection.execute("BEGIN")
            self.check(connection)
            rows = connection.execute("SELECT * FROM pilotage_decisions.entries" + where + " ORDER BY id DESC LIMIT ?",
                                      (*parameters, limit + 1)).fetchall()
            items = [self.entry(row) for row in rows[:limit]]
            return {"items": items, "has_more": len(rows) > limit,
                    "next_before_id": items[-1]["id"] if len(rows) > limit else None,
                    "coverage": self.coverage(connection, now), "execution_allowed": False,
                    "semantics": "Mesures de la premiere evaluation de chaque transition ; confirmations sans remplacement des preuves. Aucun historique reconstruit avant activation."}

    def detail(self, identifier):
        if type(identifier) is not int or not 1 <= identifier < 2**63:
            raise ValueError("Identifiant du journal invalide.")
        with self.store.connection() as connection:
            connection.execute("BEGIN")
            self.check(connection)
            row = connection.execute("SELECT * FROM pilotage_decisions.entries WHERE id=?", (identifier,)).fetchone()
            return None if row is None else self.entry(row)
